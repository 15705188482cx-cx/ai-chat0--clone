def add_time_gaps(convos):
    """会话内部消息之间加入随机时间间隔"""
    result = []
    for base_time, messages in convos:
        current_time = base_time
        expanded = []
        last_sender = None
        for sender, content in messages:
            if last_sender is not None and sender != last_sender:
                gap_sec = random.randint(10, 90)
            else:
                gap_sec = random.randint(20, 150)
            current_time += timedelta(seconds=gap_sec)
            expanded.append((current_time, sender, content))
            last_sender = sender
        result.append(expanded)
    return result


def assemble_full_dataset():
    convos = make_conversations()
    timed_convos = add_time_gaps(convos)
    all_msgs = []
    for convo in timed_convos:
        all_msgs.extend(convo)
    all_msgs.sort(key=lambda x: x[0])
    return all_msgs


def assemble_quick_dataset(all_msgs):
    subset = all_msgs[:50]
    start = datetime(2024, 3, 25, 9, 0, 0)
    result = []
    current = start
    for _, sender, content in subset:
        gap_sec = random.randint(30, 300)
        current += timedelta(seconds=gap_sec)
        result.append((current, sender, content))
    return result


def format_txt(msgs):
    lines = []
    for t, sender, content in msgs:
        lines.append(f"{t.strftime('%Y-%m-%d %H:%M:%S')} {sender}")
        lines.append(content)
        lines.append("")
    return "\n".join(lines)


def format_json(msgs):
    records = []
    for t, sender, content in msgs:
        if content in ("[图片]",):
            msg_type = "image"
        elif content in ("[视频]",):
            msg_type = "video"
        else:
            msg_type = "text"
        records.append({
            "sender_name": sender,
            "content": content,
            "time": t.strftime("%Y-%m-%d %H:%M:%S"),
            "type": msg_type
        })
    return json.dumps(records, ensure_ascii=False, indent=2)


